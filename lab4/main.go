package main

import "fmt"

func main() {
	matrixWithMatch := [][]float64{
		{-12.0, -8.5, -5.0, -9.1, -3.0, -15.0, -4.4, -7.0},
		{-10.5, -6.0, -2.3, -4.0, -1.2, -11.0, -2.0, -3.5},
		{-9.0, -4.2, -0.5, 2.5, 6.0, -7.5, -0.1, 0.0},
		{-7.2, -1.0, 5.5, 4.0, 7.1, -3.0, 1.8, 3.2},
		{-5.0, 6.1, 8.0, 6.2, 9.5, 5.1, 4.9, 5.0},
		{-2.1, 9.0, 11.4, 8.8, 12.0, 8.4, 7.3, 8.1},
		{-0.5, 14.2, 15.0, 11.5, 16.4, 12.9, 10.0, 13.7},
	}

	fmt.Println("Тест 1 (елемент у [0, 5] існує):")
	printMatrix(matrixWithMatch)

	if row, col, found := findInMatrix(matrixWithMatch); found {
		fmt.Printf("Знайдене число %.1f на позиції: рядок %d, стовпчик %d (в 1-індексації: [%d, %d])\n\n",
			matrixWithMatch[row][col], row, col, row+1, col+1)
	} else {
		fmt.Println("Чисел з діапазону [0, 5] в матриці немає.")
	}

	matrixWithoutMatch := [][]float64{
		{-10.0, -8.0, -6.0, -4.0, -2.0, -9.0, -7.0},
		{-8.5, -6.5, -4.5, -2.5, -1.0, -7.5, -5.5},
		{-6.0, -4.0, -2.0, -0.5, -0.1, -5.0, -3.0},
		{-3.2, -1.5, -0.2, 5.1, 5.5, -2.1, -0.8},
		{5.5, 6.0, 7.0, 8.0, 9.0, 6.2, 5.2},
		{8.0, 9.5, 10.2, 11.4, 12.8, 9.1, 8.4},
		{11.0, 13.0, 14.5, 15.0, 16.2, 12.5, 11.9},
	}

	fmt.Println("Тест 2 (елементів із [0, 5] немає):")
	printMatrix(matrixWithoutMatch)

	if row, col, found := findInMatrix(matrixWithoutMatch); found {
		fmt.Printf("Знайдено число %.1f на позиції [%d, %d]\n", matrixWithoutMatch[row][col], row+1, col+1)
	} else {
		fmt.Println("Чисел із діапазону [0, 5] у матриці немає.")
	}

	matrixBoundary := [][]float64{
		{-12.0, 6.0, -8.0, 5.5, -9.0, -3.0, -4.0},
		{-10.0, 7.0, -7.0, 6.0, -8.0, -2.0, -3.0},
		{-9.0, 8.0, -6.0, 7.0, -7.0, -1.0, -2.0},
		{-8.0, 9.0, -5.0, 8.0, -6.0, -0.1, -1.0},
		{-7.0, 10.0, -4.0, 9.0, -5.0, 5.1, -0.5},
		{-6.0, 11.0, -3.0, 10.0, -4.0, 7.0, 5.0},
		{-5.0, 12.0, -2.0, 11.0, -3.0, 9.0, 9.0},
	}

	fmt.Println("\nТест 3 (єдиний збіг рівно на межі 5.0, в останньому стовпчику):")
	printMatrix(matrixBoundary)

	if row, col, found := findInMatrix(matrixBoundary); found {
		fmt.Printf("Знайдене число %.1f на позиції [%d, %d]\n", matrixBoundary[row][col], row+1, col+1)
	} else {
		fmt.Println("Чисел із діапазону [0, 5] у матриці немає.")
	}
}
